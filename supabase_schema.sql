-- 1. Crear tabla de asistentes oficial
CREATE TABLE IF NOT EXISTS public.attendees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    full_name TEXT NOT NULL,
    ci TEXT DEFAULT '',
    email TEXT NOT NULL,
    phone TEXT NOT NULL,
    ticket_count INTEGER DEFAULT 1,
    ticket_list TEXT[] DEFAULT '{}',
    institution TEXT DEFAULT '',
    position TEXT DEFAULT '',
    attending TEXT DEFAULT 'yes',
    dietary TEXT[] DEFAULT '{}',
    comments TEXT DEFAULT ''
);

-- 2. Índices de alto rendimiento para búsqueda y ordenamiento ultrarrápido
CREATE INDEX IF NOT EXISTS idx_attendees_id_desc ON public.attendees (id DESC);
CREATE INDEX IF NOT EXISTS idx_attendees_ci ON public.attendees (ci);
CREATE INDEX IF NOT EXISTS idx_attendees_email ON public.attendees (email);

-- 3. Otorgar permisos completos a los roles de cliente y servicio
GRANT ALL ON TABLE public.attendees TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 4. Habilitar Row Level Security (RLS) con políticas permisivas para anon y authenticated
ALTER TABLE public.attendees ENABLE ROW LEVEL SECURITY;

-- 4.1 Permitir registro público (INSERT)
DROP POLICY IF EXISTS "Permitir registros publicos" ON public.attendees;
CREATE POLICY "Permitir registros publicos" 
ON public.attendees 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- 4.2 Permitir lectura de asistentes (SELECT)
DROP POLICY IF EXISTS "Permitir lectura publica" ON public.attendees;
CREATE POLICY "Permitir lectura publica" 
ON public.attendees 
FOR SELECT 
TO anon, authenticated 
USING (true);

-- 4.3 Permitir actualización de asistentes (UPDATE)
DROP POLICY IF EXISTS "Permitir actualizar registros" ON public.attendees;
CREATE POLICY "Permitir actualizar registros" 
ON public.attendees 
FOR UPDATE 
TO anon, authenticated 
USING (true) 
WITH CHECK (true);

-- 4.4 Permitir eliminación de asistentes (DELETE)
DROP POLICY IF EXISTS "Permitir eliminar registros" ON public.attendees;
CREATE POLICY "Permitir eliminar registros" 
ON public.attendees 
FOR DELETE 
TO anon, authenticated 
USING (true);

