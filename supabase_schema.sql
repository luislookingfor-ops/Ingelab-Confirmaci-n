-- 2. Crear tabla de asistentes oficial
CREATE TABLE IF NOT EXISTS public.attendees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    full_name TEXT NOT NULL,
    ci TEXT DEFAULT '',
    email TEXT NOT NULL,
    phone TEXT NOT NULL,
    ticket_count INTEGER DEFAULT 1,
    ticket_list TEXT[] DEFAULT '{}',
    institution TEXT DEFAULT '',
    position TEXT DEFAULT '',
    attending TEXT DEFAULT 'yes',
    dietary TEXT[] DEFAULT '{}',
    comments TEXT DEFAULT ''
);

-- ==============================================================
-- 3. PREVENCIÓN DE DUPLICADOS Y CONDICIONES DE CARRERA (RACE CONDITIONS)
-- ==============================================================

-- 3.1 Limpiar duplicados previos si existieran, conservando el registro más reciente
DELETE FROM public.attendees a
USING public.attendees b
WHERE a.id < b.id AND LOWER(TRIM(a.email)) = LOWER(TRIM(b.email));

-- 3.2 Restricción UNIQUE a nivel de base de datos por Correo Electrónico (Garantiza Idempotencia)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'unique_attendee_email'
    ) THEN
        ALTER TABLE public.attendees ADD CONSTRAINT unique_attendee_email UNIQUE (email);
    END IF;
END $$;

-- 3.3 Restricción UNIQUE parcial para Cédula/Documento (cuando se proporciona y no está vacía)
CREATE UNIQUE INDEX IF NOT EXISTS idx_attendees_unique_ci 
ON public.attendees (ci) 
WHERE ci IS NOT NULL AND trim(ci) != '';

-- 3.4 Validaciones de Integridad de Datos (Anti-Spam / Anti-Payload corrupto)
ALTER TABLE public.attendees DROP CONSTRAINT IF EXISTS check_attendee_valid_name;
ALTER TABLE public.attendees ADD CONSTRAINT check_attendee_valid_name CHECK (length(trim(full_name)) >= 3);

ALTER TABLE public.attendees DROP CONSTRAINT IF EXISTS check_attendee_valid_email;
ALTER TABLE public.attendees ADD CONSTRAINT check_attendee_valid_email CHECK (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$');

-- ==============================================================
-- 4. ÍNDICES DE RENDIMIENTO PARA ALTA CONCURRENCIA
-- ==============================================================
CREATE INDEX IF NOT EXISTS idx_attendees_id_desc ON public.attendees (id DESC);
CREATE INDEX IF NOT EXISTS idx_attendees_email_lower ON public.attendees (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_attendees_created_at ON public.attendees (created_at DESC);

-- ==============================================================
-- 5. PERMISOS Y ROW LEVEL SECURITY (RLS) SEGURO
-- ==============================================================
GRANT ALL ON TABLE public.attendees TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

ALTER TABLE public.attendees ENABLE ROW LEVEL SECURITY;

-- 5.1 Inserción pública validada (Solo registros legítimos)
DROP POLICY IF EXISTS "Permitir registros publicos" ON public.attendees;
CREATE POLICY "Permitir registros publicos" 
ON public.attendees 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (
    length(trim(full_name)) >= 3 
    AND email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'
);

-- 5.2 Lectura de asistentes para panel administrativo
DROP POLICY IF EXISTS "Permitir lectura publica" ON public.attendees;
CREATE POLICY "Permitir lectura publica" 
ON public.attendees 
FOR SELECT 
TO anon, authenticated 
USING (true);

-- 5.3 Actualización de asistentes (Gestión administrativa e Idempotencia/Upsert)
DROP POLICY IF EXISTS "Permitir actualizar registros" ON public.attendees;
CREATE POLICY "Permitir actualizar registros" 
ON public.attendees 
FOR UPDATE 
TO anon, authenticated 
USING (true) 
WITH CHECK (true);

-- 5.4 Eliminación de asistentes (Solo gestión administrativa)
DROP POLICY IF EXISTS "Permitir eliminar registros" ON public.attendees;
CREATE POLICY "Permitir eliminar registros" 
ON public.attendees 
FOR DELETE 
TO anon, authenticated 
USING (true);
